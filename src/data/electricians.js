export const getElectricianById = (id) => electricians.find(e => e.id === Number(id))

export const getElectriciansByService = (serviceSlug) =>
  electricians.filter(e => e.services.includes(serviceSlug))

export const getElectriciansByCity = (city) =>
  electricians.filter(e => e.location.city.toLowerCase() === city.toLowerCase())

export const getTopElectricians = (limit = 6) =>
  [...electricians].sort((a, b) => b.rating - a.rating).slice(0, limit)

export const getAvailableElectricians = () =>
  electricians.filter(e => e.availability.isAvailable)
