import Booking from '../models/Booking.js'
import ApiError from '../utils/ApiError.js'
import crypto from 'crypto'

/**
 * @desc    Initiate a payment for a booking
 * @route   POST /api/payments/initiate
 * @access  Private (user)
 */
export const initiatePayment = async (req, res, next) => {
  try {
    const { bookingId, method } = req.body

    if (!bookingId) throw ApiError.badRequest('Booking ID is required')

    const booking = await Booking.findById(bookingId)
      .populate('electrician', 'name profilePhoto')

    if (!booking) throw ApiError.notFound('Booking not found')
    if (booking.user.toString() !== req.user._id.toString()) {
      throw ApiError.forbidden('Not authorized')
    }

    if (booking.payment.status === 'paid') {
      throw ApiError.badRequest('Payment already completed')
    }

    const total = booking.payment.total || booking.payment.amount

    // In production, integrate with Razorpay/Stripe here
    // For now, generate a mock payment order
    const orderId = `ORD_${crypto.randomBytes(8).toString('hex').toUpperCase()}`
    const transactionId = `TXN_${crypto.randomBytes(8).toString('hex').toUpperCase()}`

    // Update booking with payment info
    booking.payment.method = method || booking.payment.method
    booking.payment.transactionId = transactionId

    if (method === 'cash') {
      // Cash on service — mark as pending, no online payment needed
      booking.payment.status = 'pending'
      await booking.save()

      return res.json({
        success: true,
        paymentType: 'cash',
        message: 'Booking confirmed. Pay after service completion.',
        orderId,
        transactionId,
        booking,
      })
    }

    // For UPI/Card — generate payment link/QR
    // In production: const order = await razorpay.orders.create(...)
    const paymentData = {
      orderId,
      transactionId,
      amount: total,
      currency: 'INR',
      // Mock UPI details
      upiId: 'apnacatalyst@upi',
      qrCodeUrl: null, // Would be generated by payment gateway
    }

    await booking.save()

    res.json({
      success: true,
      paymentType: method,
      message: 'Payment initiated',
      payment: paymentData,
      booking,
    })
  } catch (error) {
    next(error)
  }
}

/**
 * @desc    Verify payment (callback from payment gateway)
 * @route   POST /api/payments/verify
 * @access  Private (user)
 */
export const verifyPayment = async (req, res, next) => {
  try {
    const { bookingId, transactionId, paymentSignature } = req.body

    if (!bookingId) throw ApiError.badRequest('Booking ID is required')

    const booking = await Booking.findById(bookingId)
      .populate('electrician', 'name profilePhoto rating location mobile')
      .populate('user', 'name email mobile')

    if (!booking) throw ApiError.notFound('Booking not found')
    if (booking.user._id.toString() !== req.user._id.toString()) {
      throw ApiError.forbidden('Not authorized')
    }

    // In production: verify signature with Razorpay
    // const isValid = razorpay.validateWebhookSignature(...)

    // For development: auto-verify
    booking.payment.status = 'paid'
    booking.payment.paidAt = new Date()
    if (transactionId) {
      booking.payment.transactionId = transactionId
    }

    await booking.save()

    res.json({
      success: true,
      message: 'Payment verified successfully',
      booking,
    })
  } catch (error) {
    next(error)
  }
}

/**
 * @desc    Get payment status for a booking
 * @route   GET /api/payments/:bookingId/status
 * @access  Private
 */
export const getPaymentStatus = async (req, res, next) => {
  try {
    const booking = await Booking.findById(req.params.bookingId)
      .select('payment bookingId')

    if (!booking) throw ApiError.notFound('Booking not found')

    res.json({
      success: true,
      bookingId: booking.bookingId,
      payment: booking.payment,
    })
  } catch (error) {
    next(error)
  }
}
